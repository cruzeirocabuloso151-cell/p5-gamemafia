func main() {
	root := "internal/assets/library"
	count := 0
	for _, p := range pieces {
		dir := filepath.Join(root, p.Cat)
		if err := os.MkdirAll(dir, 0o755); err != nil {
			fmt.Fprintln(os.Stderr, "mkdir:", err)
			os.Exit(1)
		}
		path := filepath.Join(dir, sanitize(p.Name)+".txt")
		body := canvas(p.Lines)
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "write:", err)
			os.Exit(1)
		}
		// Sanity: count runes per line.
		for i, ln := range strings.Split(strings.TrimRight(body, "\n"), "\n") {
			if utf8.RuneCountInString(ln) != W {
				fmt.Fprintf(os.Stderr, "WARN %s line %d width=%d (want %d)\n",
					path, i+1, utf8.RuneCountInString(ln), W)
			}
		}
		count++
	}
	fmt.Printf("wrote %d pieces under %s\n", count, root)
}

func sanitize(s string) string {
	s = strings.ToLower(strings.TrimSpace(s))
	out := make([]rune, 0, len(s))
	for _, r := range s {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9':
			out = append(out, r)
		case r == ' ', r == '-', r == '_':
			out = append(out, '_')
		}
	}
	if len(out) == 0 {
		return "unnamed"
	}
	return string(out)
}
