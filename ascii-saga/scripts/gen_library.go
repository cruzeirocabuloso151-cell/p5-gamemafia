//go:build ignore

// gen_library generates the curated ASCII art library at exact canvas
// dimensions (48 cols × 20 rows). Run from the project root:
//
//	go run scripts/gen_library.go
//
// Each piece is defined as a slice of "design lines" — they get padded /
// trimmed to canvas width and the slice padded / trimmed to canvas height.
// This keeps the artwork readable in source while guaranteeing the
// embedded files satisfy the validator at runtime.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"unicode/utf8"
)

const (
	W = 48
	H = 20
)

type Piece struct {
	Cat   string
	Name  string
	Lines []string
}

func pad(s string) string {
	n := utf8.RuneCountInString(s)
	switch {
	case n == W:
		return s
	case n < W:
		return s + strings.Repeat(" ", W-n)
	default:
		// trim runewise
		out := make([]rune, 0, W)
		for _, r := range s {
			out = append(out, r)
			if len(out) == W {
				break
			}
		}
		return string(out)
	}
}

func canvas(lines []string) string {
	out := make([]string, 0, H)
	for _, ln := range lines {
		out = append(out, pad(ln))
		if len(out) == H {
			break
		}
	}
	for len(out) < H {
		out = append(out, strings.Repeat(" ", W))
	}
	return strings.Join(out, "\n") + "\n"
}

